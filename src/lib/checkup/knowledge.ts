export function getKnowledgeSnippet(id: string): KnowledgeSnippet | undefined {
  return KNOWLEDGE_SNIPPETS.find((snippet) => snippet.id === id);
}

export function findKnowledgeSnippets(keywords: string[], limit = 3): KnowledgeSnippet[] {
  const normalized = keywords.map((keyword) => keyword.trim()).filter(Boolean);
  if (normalized.length === 0) return [];
  return KNOWLEDGE_SNIPPETS.filter((snippet) =>
    normalized.some(
      (keyword) =>
        snippet.keywords.some((item) => item.includes(keyword) || keyword.includes(item)) ||
        snippet.title.includes(keyword) ||
        snippet.body.includes(keyword),
    ),
  ).slice(0, limit);
}
